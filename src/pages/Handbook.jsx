const getSectionMarkdown = (section) => {
  if (section === 'all') {
    return handbookMarkdown
  }

  const [startMarker, endMarker] = sectionRanges[section] || []

  if (!startMarker || !endMarker) {
    return handbookMarkdown
  }

  const startIndex = handbookMarkdown.indexOf(startMarker)
  const endIndex = handbookMarkdown.indexOf(endMarker)

  if (startIndex === -1 || endIndex === -1 || endIndex <= startIndex) {
    return handbookMarkdown
  }

  return handbookMarkdown.slice(startIndex, endIndex).trim()
}

